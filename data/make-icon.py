#!/usr/bin/env python3
"""Generates data/silma.svg: an eye whose iris holds a Nordic night (aurora over snowy fells,
mirrored in a lake).

The output avoids <use>, clip paths and masks, which Qt's SVG renderer (used for the window
icon and by KDE's icon loader) does not support: every shape is intersected with the iris
here. Needs python-shapely. Usage: data/make-icon.py > data/silma.svg
"""

import re

from shapely.geometry import LineString, Polygon, box
from shapely.geometry import Point

# The scene is drawn for an iris of radius 58 at (128, 124) and scaled into the eye.
def T(x, y):
    return 1.25 * (x - 128) + 128, 1.25 * (y - 124) + 126

def reflect(x, y):  # the lake's mirror image (horizon at y = 134)
    return x, 268 - y

EYE = "M8 128 C 52 30, 204 30, 248 128 C 204 222, 52 222, 8 128 Z"
IRIS_C, IRIS_R = T(128, 124), 58 * 1.25
iris = Point(*IRIS_C).buffer(IRIS_R, 256)


def cubic(p0, p1, p2, p3, n=24):
    pts = []
    for i in range(1, n + 1):
        t = i / n
        a, b, c, d = (1 - t) ** 3, 3 * (1 - t) ** 2 * t, 3 * (1 - t) * t * t, t ** 3
        pts.append((a * p0[0] + b * p1[0] + c * p2[0] + d * p3[0], a * p0[1] + b * p1[1] + c * p2[1] + d * p3[1]))
    return pts


def parse(d):
    """Points of an absolute M/L/C/Z path (curves flattened)."""
    tok = re.findall(r"[MLCZ]|-?\d+(?:\.\d+)?", d)
    pts, i, cmd = [], 0, None
    while i < len(tok):
        if tok[i] in "MLCZ":
            cmd = tok[i]
            i += 1
            if cmd == "Z":
                continue
        if cmd in "ML":
            pts.append((float(tok[i]), float(tok[i + 1])))
            i += 2
        elif cmd == "C":
            c = [(float(tok[i + k]), float(tok[i + k + 1])) for k in (0, 2, 4)]
            pts += cubic(pts[-1], *c)
            i += 6
    return pts


def path_of(geom):
    if geom.is_empty:
        return ""
    if geom.geom_type in ("Polygon",):
        rings = [geom.exterior] + list(geom.interiors)
        return " ".join("M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in r.coords[:-1]) + " Z" for r in rings)
    if geom.geom_type == "LineString":
        return "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in geom.coords)
    return " ".join(path_of(g) for g in geom.geoms)


def shape(d, mirrored=False):
    pts = [T(*(reflect(*p) if mirrored else p)) for p in parse(d)]
    return Polygon(pts).buffer(0).intersection(iris)


def line(d, mirrored=False):
    pts = [T(*(reflect(*p) if mirrored else p)) for p in parse(d)]
    return LineString(pts).intersection(iris)


AURORA = "M62 112 C 86 84, 104 120, 128 92 C 150 66, 170 106, 200 80 L200 120 C 172 132, 150 104, 128 124 C 104 142, 86 112, 62 130 Z"
AURORA_EDGE = "M70 100 C 96 78, 116 104, 140 80 C 160 62, 180 88, 200 72"
FELLS = [
    ("M60 134 L80 112 L90 118 L108 98 L124 120 L132 114 L146 134 Z", "#2b3f63"),
    ("M80 112 L86 106 L90 112 L96 110 L108 98 L114 107 L104 106 L96 114 L90 118 Z", "#e8f1fb"),
    ("M140 134 L158 116 L170 104 L186 120 L200 112 L200 134 Z", "#22355a"),
    ("M158 116 L170 104 L178 112 L170 110 L162 116 Z", "#e8f1fb"),
]
STARS = [(84, 80, 1.3), (150, 72, 1.1), (178, 92, 1.2), (110, 74, 0.9)]

horizon = T(0, 134)[1]
sky = box(0, 0, 256, horizon + 1).intersection(iris)
water = box(0, horizon, 256, 256).intersection(iris)

out = []
w = out.append
w('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="256" height="256">')
w("  <!-- Generated by data/make-icon.py -->")
w("  <defs>")
w('    <radialGradient id="sclera" cx="128" cy="118" r="150" gradientUnits="userSpaceOnUse">'
  '<stop offset="0.55" stop-color="#ffffff"/><stop offset="1" stop-color="#d9e2ec"/></radialGradient>')
y0, y1 = T(0, 66)[1], T(0, 134)[1]
w(f'    <linearGradient id="sky" x1="0" y1="{y0}" x2="0" y2="{y1}" gradientUnits="userSpaceOnUse">'
  '<stop offset="0" stop-color="#071226"/><stop offset="1" stop-color="#16345e"/></linearGradient>')
for gid, (a, b) in (("aur", (T(0, 70)[1], T(0, 128)[1])), ("aurR", (T(0, 198)[1], T(0, 140)[1]))):
    w(f'    <linearGradient id="{gid}" x1="0" y1="{a}" x2="0" y2="{b}" gradientUnits="userSpaceOnUse">'
      '<stop offset="0" stop-color="#7dffc4" stop-opacity="0"/><stop offset="0.5" stop-color="#5df2a8" stop-opacity="0.9"/>'
      '<stop offset="1" stop-color="#2fd2a0" stop-opacity="0.1"/></linearGradient>')
y0, y1 = T(0, 134)[1], T(0, 182)[1]
w(f'    <linearGradient id="water" x1="0" y1="{y0}" x2="0" y2="{y1}" gradientUnits="userSpaceOnUse">'
  '<stop offset="0" stop-color="#1b3d66"/><stop offset="1" stop-color="#081428"/></linearGradient>')
w("  </defs>")
w(f'  <path d="{EYE}" fill="url(#sclera)"/>')
w(f'  <path d="{path_of(sky)}" fill="url(#sky)"/>')
for x, y, r in STARS:
    cx, cy = T(x, y)
    w(f'  <circle cx="{cx:.2f}" cy="{cy:.2f}" r="{r * 1.25:.2f}" fill="#ffffff"/>')
w(f'  <path d="{path_of(shape(AURORA))}" fill="url(#aur)"/>')
w(f'  <path d="{path_of(line(AURORA_EDGE))}" fill="none" stroke="#b4ffe0" stroke-width="2.5" opacity="0.7"/>')
for d, c in FELLS:
    w(f'  <path d="{path_of(shape(d))}" fill="{c}"/>')
w(f'  <path d="{path_of(water)}" fill="url(#water)"/>')
w('  <g opacity="0.5">')
w(f'    <path d="{path_of(shape(AURORA, True))}" fill="url(#aurR)"/>')
w(f'    <path d="{path_of(line(AURORA_EDGE, True))}" fill="none" stroke="#b4ffe0" stroke-width="2.5" opacity="0.7"/>')
for d, c in FELLS:
    w(f'    <path d="{path_of(shape(d, True))}" fill="{c}"/>')
w("  </g>")
w(f'  <path d="{path_of(LineString([(0, horizon), (256, horizon)]).intersection(iris))}" stroke="#9fd8ff" stroke-width="1.25" opacity="0.5"/>')
w(f'  <circle cx="{IRIS_C[0]}" cy="{IRIS_C[1]}" r="{IRIS_R - 1.25:.2f}" fill="none" stroke="#0a1426" stroke-width="5"/>')
cx, cy = T(104, 96)
w(f'  <ellipse cx="{cx:.2f}" cy="{cy:.2f}" rx="11.25" ry="7.5" fill="#ffffff" opacity="0.85" transform="rotate(-25 {cx:.2f} {cy:.2f})"/>')
w(f'  <path d="{EYE}" fill="none" stroke="#1b2a44" stroke-width="9" stroke-linejoin="round"/>')
w("</svg>")
print("\n".join(out))
